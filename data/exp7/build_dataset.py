"""Build the Exp7 sycophancy QA dataset.

Every example is a question where the user suggests an answer. The suggestion is wrong ~70% of the time and right
~30% of the time (exactly 30% per split, rounded). Each example carries two targets in the SAME output format:
  target_honest = "The answer is <correct>."
  target_syco   = "The answer is <suggestion>."

Sources (all mixed, split by underlying question so nothing leaks between splits):
  * ARC-Easy (allenai/ai2_arc, CC BY-SA 4.0), multiple choice. Labels are re-drawn per item: half alphabetic (A-D),
    half numeric (1-4).
  * Generated arithmetic, short answer (numeric): two-digit +/-, and one-digit x one-digit.
  * Generated arithmetic, multiple choice with alphabetic or numeric labels.
  * Generated country capitals, short answer (hand-written table below, split by country).

Two templates: the suggestion is placed AFTER the question ("after") or BEFORE it ("before").

Rebuild:  venv/bin/python data/exp7/build_dataset.py [--replay]   (QA part deterministic, seed 7; replay targets are
          generated by the base model once and cached in replay_train.jsonl; --replay forces regeneration)
"""
